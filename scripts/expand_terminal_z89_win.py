def main() -> int:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    existing = {c["id"] for arr in data["commands"].values() for c in arr}
    added = 0
    for group, cid, syntax, copy, title, desc, example, keywords in ITEMS:
        if cid in existing:
            continue
        if keywords and keywords[0] == cid.replace("-", ""):
            pass
        data["commands"][group].append({
            "id": cid,
            "syntax": syntax,
            "copy": copy,
            "title": title,
            "desc": desc,
            "example": example,
            "note": "Windows / PowerShell 官方 cmdlet 或系统工具；参数以 Get-Help 或官方文档为准，示例在 PowerShell 7 语法下编写。",
            "keywords": [keywords[0], GROUP_NAMES[group]],
            "danger": cid in {"remove-typeData", "remove-cimsession", "pnputil", "set-clipboard"},
            "src": "builtin",
        })
        existing.add(cid)
        added += 1
    total = sum(len(v) for v in data["commands"].values())
    data["meta"]["badge"] = f"{total:,} 条全量"
    data["version"] = VERSION
    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"Windows 新增 {added} 条，当前 {total} 条 -> {PATH}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
