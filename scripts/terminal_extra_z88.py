def main() -> int:
    dry = "--dry-run" in sys.argv
    total = 0
    for p in PLATFORMS:
        path = os.path.join(OUT_DIR, f"{p}.json")
        data = json.load(open(path, encoding="utf-8"))
        ids = {c["id"] for v in data["commands"].values() for c in v}
        added = 0
        for gid, items in EXTRA[p].items():
            for item in items:
                if item["id"] in ids:
                    continue
                data["commands"].setdefault(gid, []).append(copy.deepcopy(item))
                ids.add(item["id"])
                added += 1
        before = sum(len(v) for v in data["commands"].values()) - added
        after = before + added
        data.setdefault("version", VERSION)
        data.setdefault("meta", {})["badge"] = f"{after} 条全量"
        if not dry:
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(data, fh, ensure_ascii=False, indent=1)
                fh.write("\n")
        print(f"{p}: {before} -> {after} (+{added})")
        total += added
    print("新增合计:", total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
