def main() -> int:
    dry = "--dry-run" in sys.argv
    data = json.loads(TARGET.read_text(encoding="utf-8"))
    commands = data.setdefault("commands", {})
    existing = {str(item.get("id")) for group in commands.values() for item in group}
    additions = []
    for row in ADD:
        group, cid, syntax, title, desc, note, keywords, *rest = row
        danger = bool(rest[0]) if rest else False
        if cid in existing:
            continue
        item = {
            "id": cid,
            "syntax": syntax,
            "copy": syntax,
            "title": title,
            "desc": desc,
            "example": syntax,
            "note": note,
            "keywords": keywords,
            "src": "manual",
        }
        if danger:
            item["danger"] = True
        commands.setdefault(group, []).append(item)
        existing.add(cid)
        additions.append((group, cid))

    total = sum(len(v) for v in commands.values())
    print(f"新增 {len(additions)} 条，macOS 总计 {total} 条")
    for g in ("nav", "file", "view", "perm", "proc", "net", "dev", "pkg",
              "disk", "sec", "container", "media", "os", "alias", "other"):
        print(f"  {g}: {len(commands.get(g, []))}")

    if dry:
        return 0
    if len(additions) != len(ADD):
        print(f"警告：有 {len(ADD) - len(additions)} 条 id 已存在，已跳过")

    meta = data.setdefault("meta", {})
    meta["badge"] = f"{total:,} 条全量"
    meta["summary"] = (
        "macOS 自带命令、zsh 内置、Apple 系统工具、Xcode 工具链、Homebrew "
        "与 tldr 中文命令页全量收录；覆盖 launchd、APFS、Time Machine、Keychain、"
        "网络诊断、Xcode 构建与媒体处理。"
    )
    data["version"] = VERSION
    data.setdefault("audit", {})["additions"] = [cid for _, cid in additions]
    TARGET.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"已写入 {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
